/** Course suggestion for the finder: children under 7 always start with early music. */
export function suggestCourse(age: AgeId, goal: GoalId): CourseId {
  if (age === 'kids') return 'musicalizacao';
  const child = age === 'children';
  switch (goal) {
    case 'sing-along': return child ? 'ukulele' : 'violao';
    case 'band': return child ? 'bateria' : 'guitarra';
    case 'keys': return 'piano';
    case 'voice': return 'canto';
    case 'rhythm': return 'bateria';
  }
}
